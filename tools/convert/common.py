# The MSVC spelling of a standard (`/std:`), by ISO name; None where MSVC has no switch (the
# legacy mode is what the compiler does without one).  clang-cl takes the same switches.
_MSVC_STANDARDS = {
    "c89": None,
    "c90": None,
    "c99": "/std:c11",  # MSVC has no C99 mode: C11 is the first one with __STDC_VERSION__
    "c11": "/std:c11",
    "c17": "/std:c17",
    "c18": "/std:c17",
    "c23": "/std:clatest",
    "c++98": "/std:c++14",  # /std:c++14 is the oldest mode MSVC offers
    "c++03": "/std:c++14",
    "c++11": "/std:c++14",
    "c++14": "/std:c++14",
    "c++17": "/std:c++17",
    "c++20": "/std:c++20",
    "c++23": "/std:c++latest",
    "c++26": "/std:c++latest",
}


def _iso(standard: str) -> str:
    standard = standard.lower()
    return "c" + standard[3:] if standard.startswith("gnu") else standard


def standard_statement(lang: str, standard: str, origin: str) -> Assign:
    """The `C_STD_OPTS` / `CXX_STD_OPTS` select, one per language and package: the `-std` (GNU)
    or `/std:` (MSVC, clang-cl) switch for `standard`, spelled as configure chose it (`gnu99`),
    which every target of the package and every check compiles with.  `origin` says what in the
    script set it, for the comment."""
    msvc = _MSVC_STANDARDS.get(_iso(standard))
    msvc_list = f'["{msvc}"]' if msvc else "[]"
    return Assign(
        STANDARD_CONSTANTS[lang],
        # The TODO sits inside the value: the default output drops the IR's comments
        # (`emit.strip_annotations`), and a consumer patching the entry should see it.
        Raw(
            "select({\n"
            f"    # {STANDARD_FEATURES_TODO}\n"
            f'    "@rules_cc//cc/compiler:clang-cl": {msvc_list},\n'
            f'    "@rules_cc//cc/compiler:msvc-cl": {msvc_list},\n'
            f'    "//conditions:default": ["-std={standard}"],\n'
            "})"
        ),
        comments=[
            f"{origin}: every target and check compiles in {standard} mode, as configure set CC.",
            "A consumer's --conlyopt / --cxxopt comes later on the command line and wins.",
            STANDARD_FEATURES_TODO,
        ],
    )


def no_warnings_statement() -> Assign:
    """The `NO_WARNINGS` select, one per package: upstream's warnings are not the consumer's to
    act on, and the consumer has no way to change the flags of a module it depends on."""
    return Assign(
        NO_WARNINGS,
        Raw(
            "select({\n"
            '    "@rules_cc//cc/compiler:clang-cl": ["/w"],\n'
            '    "@rules_cc//cc/compiler:msvc-cl": ["/w"],\n'
            '    "//conditions:default": ["-w"],\n'
            "})"
        ),
        comments=[
            "Warnings off on every compiler: a consumer cannot act on upstream's and cannot change",
            "the flags of a module it depends on.",
        ],
    )


_TOP_DIR_TOKENS = (
    "@top_builddir@/",
    "@top_srcdir@/",
    "@top_build_prefix@",
    "$(top_builddir)/",
    "$(top_srcdir)/",
    "${top_builddir}/",
    "${top_srcdir}/",
)
_SAME_DIR_TOKENS = ("@srcdir@/", "@builddir@/", "$(srcdir)/", "$(builddir)/", "${srcdir}/", "${builddir}/")


def makefile_relative(path: str, directory: str) -> str:
    """A path of a Makefile.am as a path relative to that Makefile's directory: automake's
    substitutions for the tree's roots (`@top_builddir@/source/x.cpp`, `$(top_srcdir)/lib/y.c`)
    point at the project root, the directory's own (`$(srcdir)/x.c`) at the directory itself;
    anything else is as written.  A substitution left inside (`@ZLIBDIR@`) stays, for the usual
    `variable:` decision."""
    for token in _TOP_DIR_TOKENS:
        if path.startswith(token):
            return os.path.relpath(path[len(token) :], directory or ".").replace(os.sep, "/")
    for token in _SAME_DIR_TOKENS:
        if path.startswith(token):
            return path[len(token) :]
    return path


def source_label(prefix: str, path: str) -> str:
    """`<package prefix><Makefile-relative path>` as a label: a path that climbs out of the
    Makefile's directory (`bin/../source/x.cpp`) is normalized to the tree path."""
    label = f"{prefix}{path}"
    return posixpath.normpath(label) if "../" in label else label


def headers_glob(patterns: list[str], *, exclude: Sequence[str] = (), indent: str = "    ") -> Raw:
    """The `glob([...], allow_empty = True)` of a headers library's `hdrs`, rendered at `indent`
    (the attribute's indent; the value's lines go one level deeper)."""
    inner = indent + "    "
    text = f"glob(\n{inner}{_list_literal(list(patterns), inner)},\n"
    if exclude:
        text += f"{inner}exclude = [\n" + "".join(f'{inner}    "{h}",\n' for h in exclude) + f"{inner}],\n"
    text += f"{inner}allow_empty = True,\n{indent})"
    return Raw(text)


def header_patterns(src: Path, dirs: Iterable[str], suffix: str = ".h") -> list[str]:
    """The glob patterns of the headers under each of `dirs`: `<dir>/**/*.h` for a named
    directory, and for the root (`""` or `"."`) `*.h` plus `<top>/**/*.h` for each top-level
    directory of `src` that holds a header.  A recursive glob is fine under a known prefix; it
    never starts at the root.  `**/*.h` from the root walks the whole tree and, when the module
    is itself the root workspace (a presubmit's `module_path: ""`), follows the `bazel-*`
    convenience symlinks of an earlier build into bazel-out and every external repository
    (readline's `top_srcdir_headers` picked up its own `_virtual_includes` tree); named
    directories never reach them.  `suffix` is `.in.h` for the templates a gnulib glob leaves
    out."""
    out: list[str] = []
    for directory in dirs:
        name = directory.rstrip("/")
        if name in ("", "."):
            out.append(f"*{suffix}")
            out += sorted(
                f"{d.name}/**/*{suffix}"
                for d in src.iterdir()
                if d.is_dir()
                and d.name != ".git"
                and not d.name.startswith("bazel-")
                and not d.is_symlink()
                and any(f.name.endswith(suffix) for f in d.rglob("*") if f.is_file())
            )
        else:
            out.append(f"{name}/**/*{suffix}")
    return list(dict.fromkeys(out))


def _list_literal(items: list[str], indent: str) -> str:
    if not items:
        return "[]"
    if len(items) == 1:
        return f'["{items[0]}"]'
    inner = indent + "    "
    return "[\n" + "".join(f'{inner}"{item}",\n' for item in items) + indent + "]"


def _dict_of_lists(items: dict[str, list[str]], indent: str) -> str:
    inner = indent + "    "
    lines = ["{"]
    for key, values in dict_items(items):
        lines.append(f'{inner}"{key}": {_list_literal(values, inner)},')
    lines.append(indent + "}")
    return "\n".join(lines)


def _dict_literal(items: dict[str, str], indent: str) -> str:
    inner = indent + "    "
    lines = ["{"]
    for key, value in dict_items(items):
        lines.append(f'{inner}"{key}": "{value}",')
    lines.append(indent + "}")
    return "\n".join(lines)
