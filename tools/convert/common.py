def _banner_text(title: str, what: str) -> str:
    return (
        f"DO NOT MODIFY: {title}'s {what}, generated by rules_cc_autoconf from configure.ac and the "
        "Makefile.am files with the choices in decisions.bzl. To regenerate, from a clone of "
        "rules_cc_autoconf:"
    )


def generated_banner(title: str, what: str, command: str | None = None) -> str:
    """The comment block at the top of a generated Starlark file: the `@generated` marker on
    its own line (what review tools collapse files on, and the converter's ownership mark with
    the name rules_cc_autoconf), what the file is, the command that regenerates it, the docs."""
    rule = "#" * 79
    return "\n".join(
        [rule, f"# {GENERATED_MARK}"]
        + [f"# {line}" for line in textwrap.wrap(_banner_text(title, what), 77)]
        + ["#", f"#     {command or DEFAULT_COMMAND}", "#", f"# {CONVERT_DOCS}", rule]
    )


def generated_docstring(title: str, what: str, command: str | None = None) -> str:
    """The same, as the text of a module docstring (a `.bzl` file opens with one): the marker,
    what the file is and how BUILD.bazel beside it relates, the command, the docs."""
    return "\n".join(
        [
            *textwrap.wrap(_banner_text(title, what), 79),
            "",
            f"    {command or DEFAULT_COMMAND}",
            "",
            *textwrap.wrap(
                f"{GENERATED_MARK}. BUILD.bazel beside this file is hand-written: it loads this file and "
                "calls autoconf_targets(), and a rule it declares with a generated target's name replaces "
                "that target here.",
                79,
            ),
            "",
            CONVERT_DOCS,
        ]
    )


