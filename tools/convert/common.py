def _compatible_with(platforms: list[str], *, only: bool) -> Raw:
    """`target_compatible_with` as a select(): compatible on `platforms` only (`only=True`), or
    everywhere but on them."""
    incompatible = ["@platforms//:incompatible"]
    # `!L1,L2` (an `else` branch's arm): compatible everywhere but on those labels.
    if only and len(platforms) == 1 and platforms[0].startswith("!"):
        platforms, only = platforms[0][1:].split(","), False
    arms = {label: ([] if only else incompatible) for label in sorted(platforms)}
    arms[lower.DEFAULT_ARM] = incompatible if only else []
    return Raw(f"select({_dict_of_lists(arms, '    ')})")


_GNULIB_MODULE_RE = re.compile(r"^\s*# Code from module ([A-Za-z0-9_.+-]+):", re.MULTILINE)


def _gnulib_modules(src: Path) -> set[str]:
    """The gnulib modules gnulib-tool listed in the tree's gnulib-comp.m4 files (`# Code from
    module verror:`), the modules without a source or an m4 file included."""
    out: set[str] = set()
    for comp in src.glob("**/gnulib-comp.m4"):
        out |= set(_GNULIB_MODULE_RE.findall(comp.read_text(encoding="utf-8", errors="replace")))
    return out


def _pure_os_arms(cond: df.Cond | None) -> dict[str, df.Cond] | None:
    """The host-OS arms of a condition that is only about the host OS (every arm's residual a
    constant); None for no condition, one without a host_os atom, or one a probe also decides."""
    if cond is None or not df.host_os_atoms(cond):
        return None
    arms = lower.os_arms(cond)
    if any(residual not in (df.TRUE, df.FALSE) for residual in arms.values()):
        return None
    return arms


def _platform_exceptions(cond: df.Cond | None) -> list[str] | None:
    """For a purely host-OS condition that holds everywhere but on a few
    platforms (`case $host_os in openbsd* | aix* | *-android*) false;; *) true`),
    the constraint labels it does not hold on; None for any other condition.
    Patterns no Bazel constraint names (aix*) are not platforms Bazel builds
    for and drop out."""
    arms = _pure_os_arms(cond)
    if arms is None:
        return None
    if arms.get(lower.DEFAULT_ARM) is not df.TRUE:
        return None
    return sorted(label for label, residual in arms.items() if residual is df.FALSE and label != lower.DEFAULT_ARM)


def _platform_labels(cond: df.Cond | None) -> list[str] | None:
    """The constraint labels under which a purely host-OS condition holds, or
    None when the condition is not (only) about the host OS."""
    arms = _pure_os_arms(cond)
    if arms is None or cond is None:
        return None
    # A pattern that tells the systems of one constraint apart (`*-gnu*` is
    # linux-gnu but not linux-musl) is not a platform condition.  `mingw*` alone is
    # native Windows as a gnulib before 2024 spelled it (bison's `case "$host_os" in
    # mingw*) AC_LIBOBJ([windows-once])`): the `windows` host stands with the mingw ones
    # unless some pattern names it.
    spells_windows = any(
        df.substitute_host_os(df.HostOs((pattern,)), "windows") is df.TRUE
        for atom in df.host_os_atoms(cond)
        for pattern in atom.patterns
    )
    for _label, hosts in lower.OS_CONSTRAINTS:
        considered = [h for h in hosts if h != "windows" or spells_windows]
        verdicts = {df.substitute_host_os(cond, host) for host in considered}
        if len(verdicts) > 1:
            return None
    if arms.get(lower.DEFAULT_ARM) is df.TRUE:
        return None  # holds everywhere but a few platforms: not a plain select list
    return [label for label, residual in arms.items() if residual is df.TRUE and label != lower.DEFAULT_ARM]


