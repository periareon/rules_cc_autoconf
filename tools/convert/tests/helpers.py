"""What the converter's tests share: writing a fixture file, the banners that mark a file as
the converter's own (`ownership.is_owned` needs both `@generated` and rules_cc_autoconf), and
the narrowing of optional results a test expects to be there."""

from __future__ import annotations

from pathlib import Path

from tools.convert.ir import AttrValue, Call, CheckItem, Raw

OURS = "# @generated by rules_cc_autoconf convert; do not edit.\n"
"""The mark as a comment line, the form of a BUILD file's banner."""

OURS_DOCSTRING = '"""x: generated by rules_cc_autoconf convert.\n\n@generated from configure.ac"""\n'
"""The mark inside a leading docstring, the form of a generated file with one."""


def write(path: Path, text: str) -> None:
    """Write `text` to `path`, creating its directories."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def must[T](value: T | None) -> T:
    """`value`, which the test expects a lookup to have found: fails on None."""
    assert value is not None
    return value


def as_call(value: AttrValue) -> Call:
    """An argument or attribute value the test expects to be a nested Call (a `code` program)."""
    assert isinstance(value, Call), value
    return value


def as_raw(value: AttrValue) -> Raw:
    """An attribute value the test expects to be a Raw expression (a `select()`, a constant)."""
    assert isinstance(value, Raw), value
    return value


def as_str(value: AttrValue) -> str:
    """An argument or attribute value the test expects to be a string."""
    assert isinstance(value, str), value
    return value


def calls(items: list[CheckItem]) -> list[Call]:
    """The checks of a target or arm, which the test expects to be Calls only (no Raw)."""
    found = [item for item in items if isinstance(item, Call)]
    assert len(found) == len(items), items
    return found
