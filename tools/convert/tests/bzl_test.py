"""Tests for the second rendering: autoconf.bzl from the BUILD text, and the hand-written BUILD.bazel."""

from __future__ import annotations

import textwrap

from tools.convert import bzl

BUILD_TEXT = textwrap.dedent('''\
    """gzip 1.15's targets.

    @generated by rules_cc_autoconf
    """

    load("@bazel_skylib//rules:common_settings.bzl", "bool_flag")
    load("@rules_cc//cc:cc_library.bzl", "cc_library")
    load("@rules_cc_autoconf//autoconf:autoconf.bzl", "autoconf")

    exports_files(["COPYING"])

    NO_WARNINGS = select({
        "@rules_cc//cc/compiler:msvc-cl": ["/w"],
        "//conditions:default": ["-w"],
    })

    COPTS = NO_WARNINGS + ["-DX"]

    # The optional parts.
    BOOL_OPTIONS = {
        "nls": True,
    }

    [
        bool_flag(
            name = name,
            build_setting_default = default,
            visibility = ["//visibility:public"],
        )
        for name, default in BOOL_OPTIONS.items()
    ]

    [
        config_setting(
            name = name + "_enabled",
            flag_values = {":" + name: "True"},
        )
        for name, default in BOOL_OPTIONS.items()
    ]

    package(default_package_metadata = [":package_metadata"])

    SRC_HDRS = glob(["src/*.h"])

    ALL_HDRS = SRC_HDRS + ["x.h"]

    # Read by a target BUILD.bazel replaced.
    UNREAD_HDRS = glob(["unread/*.h"])

    # The configured header.
    autoconf(
        name = "autoconf",
        checks = [],
        out = "config.h",
    )

    cc_library(
        name = "gzip",
        srcs = ["gzip.c"] + ALL_HDRS,
        copts = COPTS,
        deps = [":autoconf"],
    )

    genrule(
        name = "version_h",
        outs = ["version.h"],
        cmd = """\\
    echo a
      echo b > $@""",
    )

    alias(
        name = "z",
        actual = ":gzip",
    )
''')


def test_to_bzl() -> None:
    """A BUILD text as autoconf.bzl: docstring and loads on top, then `visibility("private")`;
    the constants free of glob() stay at the top level (loadable by BUILD.bazel), the others
    move into the macro with whatever reads them; bare natives get `native.`; comprehension
    statements become `for` loops with unread loop variables underscored; a multi-line string
    keeps its columns; the replaced targets are named in the macro's docstring."""
    text = bzl.to_bzl(BUILD_TEXT, replaced=["gzip"])
    head, _, body = text.partition("def autoconf_targets():\n")
    assert head.startswith('"""gzip 1.15\'s targets.\n\n@generated by rules_cc_autoconf\n"""\n\nload(')
    assert head.index("@rules_cc_autoconf//autoconf:autoconf.bzl") < head.index('visibility("private")')
    assert "\nNO_WARNINGS = select({\n" in head
    assert '\nCOPTS = NO_WARNINGS + ["-DX"]\n' in head
    assert "\n# The optional parts.\nBOOL_OPTIONS = {\n" in head
    assert head.rstrip().endswith("# buildifier: disable=unnamed-macro")
    assert "SRC_HDRS" not in head and "ALL_HDRS" not in head
    assert body.startswith(
        '    """The targets configure.ac and the Makefile.am files describe, in the package that calls '
        'this.\n\n    Left out, since BUILD.bazel declares them: gzip.\n    """\n'
    )
    assert '    native.exports_files(["COPYING"])\n' in body
    assert "    for name, default in BOOL_OPTIONS.items():\n        bool_flag(\n            name = name," in body
    assert "    for name, _default in BOOL_OPTIONS.items():\n        native.config_setting(\n" in body
    assert '    SRC_HDRS = native.glob(["src/*.h"])\n\n    ALL_HDRS = SRC_HDRS + ["x.h"]\n' in body
    assert "UNREAD_HDRS" not in text  # read by nothing left in the macro: an unused variable
    assert "    # buildifier: disable=native-package\n    native.package(default_package_metadata" in body
    assert '    # The configured header.\n    autoconf(\n        name = "autoconf",\n' in body
    assert (
        '    native.genrule(\n        name = "version_h",\n        outs = ["version.h"],\n        cmd = """\\\necho a\n  echo b > $@""",\n    )'
        in body
    )
    assert body.rstrip().endswith('    native.alias(\n        name = "z",\n        actual = ":gzip",\n    )')
    assert "native.select" not in text
    top, inner = bzl.assigned_names(text)
    assert top == {"NO_WARNINGS", "COPTS", "BOOL_OPTIONS"}
    assert inner == {"SRC_HDRS", "ALL_HDRS"}
    assert bzl.to_bzl('load("@rules_cc//cc:cc_library.bzl", "cc_library")\n').endswith(
        'def autoconf_targets():\n    """The targets configure.ac and the Makefile.am files describe, in the package '
        'that calls this."""\n\n    pass\n'
    )


def test_build_file() -> None:
    """The hand-written BUILD.bazel as first written: the stub alone, or an additive file of the
    earlier layout moved in, its docstring first, its loads merged with the autoconf.bzl load
    (which names the top-level constants the text reads), the macro call once."""
    stub = bzl.build_file()
    assert stub.startswith('load(":autoconf.bzl", "autoconf_targets")\n\n# The targets of configure.ac')
    assert stub.rstrip().endswith("autoconf_targets()")
    additions = textwrap.dedent('''\
        """Hand-written additions:
        the tests."""

        load("@rules_shell//shell:sh_test.bzl", "sh_test")
        load(
            "@bazel_skylib//rules:diff_test.bzl",
            "diff_test",
        )
        load("@rules_cc//cc:cc_binary.bzl", "cc_binary")

        # The smoke test.
        sh_test(
            name = "smoke",
            srcs = ["smoke.sh"],
            data = [":gzip"],
        )

        cc_binary(
            name = "gzip",
            srcs = ["gzip.c"],
            copts = NO_WARNINGS,
        )
        ''')
    text = bzl.build_file(additions, symbols=["NO_WARNINGS"])
    assert text.startswith(
        '"""Hand-written additions:\nthe tests."""\n\nload(":autoconf.bzl", "NO_WARNINGS", "autoconf_targets")\n'
    )
    assert (
        'load(\n    "@bazel_skylib//rules:diff_test.bzl",\n    "diff_test",\n)\nload("@rules_cc//cc:cc_binary.bzl", "cc_binary")\n'
        'load("@rules_shell//shell:sh_test.bzl", "sh_test")\n\n# The targets of configure.ac' in text
    )
    assert text.index("autoconf_targets()\n") < text.index("# The smoke test.\nsh_test(")
    assert text.count("autoconf_targets()") == 1
    assert text.rstrip().endswith(")")
    # A BUILD.bazel that already calls the macro, with an additive file appended: one call.
    merged = bzl.build_file(stub + "\n" + additions)
    assert merged.count("autoconf_targets()") == 1
    assert merged.count("load(") == 4
    # The loads the hand text leaned on the generated file for, from autoconf.bzl's.
    bzl_text = (
        'load("@rules_cc//cc:cc_binary.bzl", "cc_binary")\nload("@rules_cc//cc:cc_library.bzl", "cc_library")\n'
        'load("@rules_cc_autoconf//autoconf:checks.bzl", "checks", "macros")\n'
    )
    hand = (
        'autoconf_hdr(name = "h", checks = [checks.AC_DEFINE("X", 1)])\ncc_library(name = "l", srcs = glob(["*.c"]))\n'
        'cc_test(name = "t")\nbool_flag(name = "f")\n'
    )
    # cc_library and checks from autoconf.bzl's loads; autoconf_hdr and bool_flag, which it no
    # longer loads (BUILD.bazel took their only users), from the known rules; cc_test unknown.
    assert bzl.loads_needed(hand, bzl_text) == [
        'load("@bazel_skylib//rules:common_settings.bzl", "bool_flag")',
        'load("@rules_cc//cc:cc_library.bzl", "cc_library")',
        'load("@rules_cc_autoconf//autoconf:autoconf_hdr.bzl", "autoconf_hdr")',
        'load("@rules_cc_autoconf//autoconf:checks.bzl", "checks")',
    ]
    assert bzl.build_file(hand, loads=bzl.loads_needed(hand, bzl_text)).startswith(
        'load(":autoconf.bzl", "autoconf_targets")\nload("@bazel_skylib//rules:common_settings.bzl", "bool_flag")\n'
        'load("@rules_cc//cc:cc_library.bzl", "cc_library")\n'
        'load("@rules_cc_autoconf//autoconf:autoconf_hdr.bzl", "autoconf_hdr")\n'
        'load("@rules_cc_autoconf//autoconf:checks.bzl", "checks")\n'
    )


def test_names_used() -> None:
    """The names a hand text reads: rules called, namespaces read, constants used; comments and
    strings do not count, and a text Python rejects falls back to its identifiers."""
    text = """# NO_WARNINGS is mentioned here only.
cc_library(name = "l", copts = COPTS, srcs = ["NOT_A_NAME.c"], deps = select({":a": [":b"]}))
checks.AC_DEFINE("X", 1)
"""
    assert bzl.names_used(text) == {"cc_library", "COPTS", "select", "checks"}
    assert {"foo", "BAR"} <= bzl.names_used("foo(name = x,)\nif BAR:\n")
